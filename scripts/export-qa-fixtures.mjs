import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { buildCoverageReport } from '../src/coverage-report.js';
import { buildPathIndex, calculateCoverage } from '../src/path-index.js';
import { SaveType, encodeSaveData } from '../src/save-codec.js';
import { analyzeSaveData } from '../src/save-analysis.js';
import { createComprehensiveAndroidSave, createComprehensivePcSave } from './fixture-saves.mjs';

const FIXTURE_GENERATED_AT = '2026-06-02T00:00:00.000Z';
const PUBLIC_TEST_URL = 'https://beurke1.github.io/antimatter-dimensions-mobile-save-editor/';

const stringifyJson = (value) => `${JSON.stringify(value, null, 2)}\n`;

const readmeText = `# QA Fixtures

These synthetic late-game saves are generated by \`npm run qa:fixtures\`.
They are not real user saves and should only be used for repeatable coverage and mobile UI checks.

## Files

- \`pc-late-game-save.txt\`: encoded PC-format fixture save.
- \`android-late-game-save.txt\`: encoded Android-format fixture save.
- \`pc-coverage-report.json\`: expected coverage summary for the PC fixture.
- \`android-coverage-report.json\`: expected coverage summary for the Android fixture.
- \`manifest.json\`: compact index of fixture expectations.

## Manual QA

Open ${PUBLIC_TEST_URL} on the target device, paste a fixture save into Import, and tap Decode.
The app should show the matching path totals from \`manifest.json\`, no safety errors, category tabs with every non-fallback category represented, and a Readiness state that allows encoding.
`;

const fixtureDefinitions = [
  {
    id: 'pc-late-game',
    saveType: SaveType.PC,
    saveFile: 'pc-late-game-save.txt',
    reportFile: 'pc-coverage-report.json',
    createData: createComprehensivePcSave,
  },
  {
    id: 'android-late-game',
    saveType: SaveType.Android,
    saveFile: 'android-late-game-save.txt',
    reportFile: 'android-coverage-report.json',
    createData: createComprehensiveAndroidSave,
  },
];

export const createQaArtifacts = async () => {
  const files = [];
  const manifest = {
    schemaVersion: 1,
    generatedAt: FIXTURE_GENERATED_AT,
    publicTestUrl: PUBLIC_TEST_URL,
    fixtures: [],
  };

  for (const definition of fixtureDefinitions) {
    const saveData = definition.createData();
    const encodedSave = await encodeSaveData(saveData, definition.saveType);
    const nodes = buildPathIndex(saveData, definition.saveType);
    const coverage = calculateCoverage(nodes);
    const analysisIssues = analyzeSaveData(saveData, definition.saveType);
    const report = buildCoverageReport({
      saveType: definition.saveType,
      nodes,
      coverage,
      changes: [],
      analysisIssues,
      generatedAt: FIXTURE_GENERATED_AT,
    });

    files.push({
      path: definition.saveFile,
      content: `${encodedSave}\n`,
    });
    files.push({
      path: definition.reportFile,
      content: stringifyJson(report),
    });

    manifest.fixtures.push({
      id: definition.id,
      saveType: definition.saveType,
      saveFile: definition.saveFile,
      coverageReportFile: definition.reportFile,
      expectedTotals: report.totals,
      expectedSafety: report.safety,
      missingCategories: report.missingCategories,
      categoryCounts: report.categories,
      stageCounts: report.stages,
    });
  }

  files.push({
    path: 'manifest.json',
    content: stringifyJson(manifest),
  });
  files.push({
    path: 'README.md',
    content: readmeText,
  });

  return {
    files,
    manifest,
  };
};

export const writeQaArtifacts = async (outputDirectory = new URL('../qa-fixtures/', import.meta.url)) => {
  const outputPath = outputDirectory instanceof URL ? fileURLToPath(outputDirectory) : outputDirectory;
  const artifacts = await createQaArtifacts();

  await mkdir(outputPath, { recursive: true });

  for (const file of artifacts.files) {
    await writeFile(join(outputPath, file.path), file.content, 'utf8');
  }

  return artifacts;
};

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { files, manifest } = await writeQaArtifacts();
  const fixtureSummary = manifest.fixtures
    .map((fixture) => `${fixture.id}: ${fixture.expectedTotals.paths} paths`)
    .join(', ');

  console.log(`Wrote ${files.length} QA fixture files to qa-fixtures/.`);
  console.log(`Fixture coverage: ${fixtureSummary}.`);
}
