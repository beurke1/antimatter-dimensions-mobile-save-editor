export const createQaArtifacts = async () => {
  const files = [];
  const manifest = {
    schemaVersion: 1,
    generatedAt: FIXTURE_GENERATED_AT,
    publicTestUrl: PUBLIC_TEST_URL,
    fixtures: [],
  };

  for (const definition of fixtureDefinitions) {
    const saveData = definition.createData();
    const encodedSave = await encodeSaveData(saveData, definition.saveType);
    const nodes = buildPathIndex(saveData, definition.saveType);
    const coverage = calculateCoverage(nodes);
    const analysisIssues = analyzeSaveData(saveData, definition.saveType);
    const report = buildCoverageReport({
      saveType: definition.saveType,
      gameStage: definition.gameStage,
      nodes,
      coverage,
      changes: [],
      analysisIssues,
      generatedAt: FIXTURE_GENERATED_AT,
    });

    files.push({
      path: definition.saveFile,
      content: `${encodedSave}\n`,
    });
    files.push({
      path: definition.reportFile,
      content: stringifyJson(report),
    });

    manifest.fixtures.push({
      id: definition.id,
      gameStage: definition.gameStage,
      saveType: definition.saveType,
      saveFile: definition.saveFile,
      coverageReportFile: definition.reportFile,
      expectedTotals: report.totals,
      expectedSafety: report.safety,
      missingCategories: report.missingCategories,
      categoryCounts: report.categories,
      stageCounts: report.stages,
    });
  }

  files.push({
    path: 'manifest.json',
    content: stringifyJson(manifest),
  });
  files.push({
    path: 'README.md',
    content: readmeText,
  });

  return {
    files,
    manifest,
  };
};

export const writeQaArtifacts = async (outputDirectory = new URL('../qa-fixtures/', import.meta.url)) => {
  const outputPath = outputDirectory instanceof URL ? fileURLToPath(outputDirectory) : outputDirectory;
  const artifacts = await createQaArtifacts();

  await mkdir(outputPath, { recursive: true });

  for (const file of artifacts.files) {
    await writeFile(join(outputPath, file.path), file.content, 'utf8');
  }

  return artifacts;
};

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { files, manifest } = await writeQaArtifacts();
  const fixtureSummary = manifest.fixtures
    .map((fixture) => `${fixture.id}: ${fixture.expectedTotals.paths} paths`)
    .join(', ');

  console.log(`Wrote ${files.length} QA fixture files to qa-fixtures/.`);
  console.log(`Fixture coverage: ${fixtureSummary}.`);
}
